class DeclensionTest(unittest.TestCase):
    def test_reference_names(self):
        errors = []
        for line in CASES.strip().splitlines():
            fio, gen, ins = line.split("|")
            got_gen, got_ins = owners.decline_fio(fio, "gen"), owners.decline_fio(fio, "ins")
            if got_gen != gen:
                errors.append(f"{fio}: родительный {got_gen!r}, ожидалось {gen!r}")
            if got_ins != ins:
                errors.append(f"{fio}: творительный {got_ins!r}, ожидалось {ins!r}")
        self.assertEqual(errors, [])

    def test_initials_gender(self):
        self.assertEqual(owners.decline_fio("Соколова С. Н.", "gen"), "Соколовой С. Н.")
        self.assertEqual(owners.decline_fio("Шевцов А А", "ins"), "Шевцовым А А")

    def test_uppercase_input(self):
        self.assertEqual(owners.decline_fio("БЕЛЯЕВА АНЖЕЛИКА ВАЛЕРЬЕВНА", "gen"), "Беляевой Анжелики Валерьевны")


