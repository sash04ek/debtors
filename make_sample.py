"""Создаёт пример входного файла sample.xlsx для проверки."""
import random
from openpyxl import Workbook

random.seed(1)
wb = Workbook(); ws = wb.active; ws.title = "Должники"
ws.append(["Реестр задолженности на 01.09.2026"]); ws.append([])
ws.append(["№", "Должник", "ИНН", "Лицевой счёт", "Сумма задолженности, руб.", "Дата образования"])
fam = ["Иванов", "Петров", "Сидоров", "Кузнецов", "Смирнов", "Попов", "Лебедев", "Козлов", "Новиков", "Морозов", "Волков", "Соколов"]
names = ["Иван Иванович", "Пётр Сергеевич", "Анна Викторовна", "Олег Павлович", "Мария Олеговна"]
orgs = ['ООО "Ромашка"', "АО «Вектор»", "ИП Федоров Андрей Николаевич", "МУП Водоканал", "ТСЖ Солнечный", "Общество с ограниченной ответственностью Лидер", "ПАО Сбытовая компания"]
n = 1
for i in range(60):
    ws.append([n, f"{random.choice(fam)} {random.choice(names)}", str(random.randint(10**11, 10**12-1)), f"ЛС-{1000+i}",
               random.choice([round(random.uniform(500, 400000), 2), f"{random.randint(1000,300000):,} руб.".replace(",", " "), f"{random.randint(1000,99999)},50"]),
               "2025-01-15"]); n += 1
for o in orgs:
    ws.append([n, o, str(random.randint(10**9, 10**10-1)), f"ЛС-{2000+n}", round(random.uniform(500000, 5000000), 2), "2024-06-01"]); n += 1
ws.append([n, "Заоева Ирина Петровна", "", "ЛС-9999", 999999, ""]); n += 1   # «АО» внутри фамилии — должна остаться
ws.append([n, "Нулёв Нуль Нулевич", "", "ЛС-0", 0, ""])
wb.save("sample.xlsx")
